#!/usr/bin/env python3
"""Turns the HTML templates, stylesheet and icon in this folder into ../pages.h for the sketch.

Run it after editing any file in web/:

    python3 web/build_pages.py

For each page.html it writes a PAGE_HTML string constant, and for each name.css or
name.svg a NAME_CSS / NAME_SVG constant that the sketch serves at /name.css or /name.svg.
Inside a template:

  <link rel="stylesheet" href="style.css">, <link rel="icon" href="favicon.svg" ...>
                                    stay links, with ?v=<hash of the file> added.
                                    The sketch tells browsers to keep these files
                                    for good, and the hash changes whenever a file
                                    does, so an edited one is fetched afresh.
                                    (Plain links also keep the template styled when
                                    opened straight from web/ in a browser.)
  <!-- begin:name --> ... <!-- end:name -->
                                    is cut out into its own NAME_HTML constant and
                                    left behind in the page as {{NAME}}, so the
                                    sketch can fill it with repeated or optional
                                    content (e.g. one row per alarm).
  {{SOMETHING}}                     is left as-is for the sketch to fill in when it sends the page.

Lines are trimmed and blank lines and comments dropped to save flash.
"""

import hashlib
import re
from pathlib import Path

WEB_DIR = Path(__file__).resolve().parent
OUT_FILE = WEB_DIR.parent / "pages.h"

LINKED_FILE = re.compile(r'(<link rel="(?:stylesheet|icon)" href=")([^"?]+)(")')
FRAGMENT = re.compile(r"<!--\s*begin:(\w+)\s*-->(.*?)<!--\s*end:\1\s*-->", re.S)
COMMENT = re.compile(r"<!--.*?-->|/\*.*?\*/", re.S)
DELIMITER = "PAGE"


def minify(text):
    text = COMMENT.sub("", text)
    lines = (line.strip() for line in text.splitlines())
    return "\n".join(line for line in lines if line)


def constant(name, text):
    if f'){DELIMITER}"' in text:
        raise SystemExit(f"{name}: content contains the raw string delimiter")
    placeholders = sorted(set(re.findall(r"\{\{(\w+)\}\}", text)))
    note = f"// placeholders: {', '.join(placeholders)}\n" if placeholders else ""
    return f'{note}const char {name}[] = R"{DELIMITER}({text}){DELIMITER}";\n'


def linked_file(path):
    """Returns (NAME_CSS or NAME_SVG, minified contents) for a file the pages link to."""
    return f"{path.stem.upper()}_{path.suffix[1:].upper()}", minify(path.read_text())


def version(text):
    return hashlib.sha1(text.encode()).hexdigest()[:8]


def templates(path):
    """Returns [(NAME_HTML, minified html), ...] for one page: the page first, then its fragments."""
    html = path.read_text()
    html = LINKED_FILE.sub(lambda m: f"{m[1]}{m[2]}?v={version(linked_file(WEB_DIR / m[2])[1])}{m[3]}", html)

    fragments = []

    def cut(match):
        name = match.group(1).upper()
        fragments.append((f"{name}_HTML", minify(match.group(2))))
        return "{{" + name + "}}"

    html = FRAGMENT.sub(cut, html)
    return [(f"{path.stem.upper()}_HTML", minify(html))] + fragments


def all_templates():
    """Every template, stylesheet and icon in web/, as {NAME_HTML / NAME_CSS / NAME_SVG: text}.
    Also used by mock_server.py."""
    files = dict(t for path in sorted(WEB_DIR.glob("*.html")) for t in templates(path))
    files.update(linked_file(path) for path in sorted([*WEB_DIR.glob("*.css"), *WEB_DIR.glob("*.svg")]))
    return files


def main():
    parts = [
        "// Generated by web/build_pages.py from the files in web/. Do not edit by hand.\n",
        "#ifndef PAGES_H\n#define PAGES_H\n",
    ]
    for name, text in all_templates().items():
        parts.append(constant(name, text))
    parts.append("#endif\n")
    OUT_FILE.write_text("\n".join(parts))
    print(f"wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
